import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

test('fluxo principal salva, reorganiza e limpa o rascunho', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Crie seu currículo profissional grátis')
  await page.getByRole('link', { name: 'Criar meu currículo' }).click()
  const name = page.getByLabel('Nome completo')
  await page.getByRole('button', { name: 'Baixar PDF' }).click()
  await expect(name).toBeFocused()
  await expect(page.getByText('Informe seu nome completo.')).toBeVisible()
  await name.fill('Júlia Nunes')
  await page.getByLabel('E-mail').fill('incompleto')
  await page.getByRole('button', { name: 'Baixar PDF' }).click()
  await expect(page.getByText('Informe um e-mail válido.')).toBeVisible()
  await page.getByLabel('E-mail').fill('julia@example.com')
  await page.getByLabel('Modelo', { exact: true }).selectOption('executivo')
  const add = page.getByRole('button', { name: 'Adicionar competência' })
  await add.press('Enter')
  await page.getByRole('textbox', { name: 'Competência', exact: true }).nth(0).fill('Excel')
  await add.press('Enter')
  await page.getByRole('textbox', { name: 'Competência', exact: true }).nth(1).fill('SQL')
  await page.getByRole('button', { name: 'Subir competência 2' }).press('Enter')
  const skills = page.getByRole('textbox', { name: 'Competência', exact: true })
  await expect(skills.nth(0)).toHaveValue('SQL')
  await expect(skills.nth(0)).toBeFocused()
  await expect(page.getByRole('status').filter({ hasText: 'Rascunho salvo' })).toBeVisible()
  await page.reload()
  await expect(name).toHaveValue('Júlia Nunes')
  await expect(skills.nth(0)).toHaveValue('SQL')
  await expect(skills.nth(1)).toHaveValue('Excel')
  await expect(page.getByLabel('Modelo', { exact: true })).toHaveValue('executivo')
  await page.getByRole('button', { name: 'Remover competência 2' }).click()
  await expect(skills).toHaveCount(1)
  await page.getByRole('button', { name: 'Limpar dados' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(name).toHaveValue('Júlia Nunes')
  await page.getByRole('button', { name: 'Limpar dados' }).click()
  await page.getByRole('button', { name: 'Limpar e começar outro' }).click()
  await page.reload()
  await expect(name).toHaveValue('')
  await expect(skills).toHaveCount(0)
  await expect(page.getByLabel('Modelo', { exact: true })).toHaveValue('classico')
})

test('editor cabe na tela pequena e alterna para a prévia', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/editor/')
  await page.getByLabel('Nome completo').fill('Luís da Costa')
  await expect(page.getByRole('region', { name: 'Prévia do currículo' })).toBeHidden()
  await page.getByRole('button', { name: 'Prévia', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Prévia do currículo' })).toBeVisible()
  await expect(page.getByRole('group', { name: 'Texto da página 1' })).toContainText('Luís da Costa')
  await expect(page.getByLabel('Nome completo')).toBeHidden()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await page.getByRole('button', { name: 'Editar', exact: true }).click()
  await expect(page.getByLabel('Nome completo')).toHaveValue('Luís da Costa')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
})

test('landing funciona com JavaScript desativado', async ({ browser }) => {
  const context = await browser.newContext({ javaScriptEnabled: false })
  const page = await context.newPage()
  await page.goto('http://127.0.0.1:4173/')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Criar meu currículo' })).toHaveAttribute('href', '/editor/')
  await context.close()
})

for (const path of ['/', '/editor/']) {
  test('acessibilidade básica em ' + path, async ({ page }) => {
    await page.goto(path)
    const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
    expect(results.violations).toEqual([])
  })
}
